/**
 * main.c — FRDM-MCXN947 application entry point.
 *
 * Reads a 5-column sensor CSV over UART (or from SD card — see INPUT_SOURCE),
 * runs the CWT + CNN pipeline, and prints the predicted tool wear in µm.
 *
 * Hardware: NXP FRDM-MCXN947  (Cortex-M33, 512 KB SRAM, 2 MB flash)
 * SDK:      MCUXpresso SDK with eIQ middleware and CMSIS-DSP
 *
 * Build flags (MCUXpresso project properties → C/C++ Build → Settings):
 *   -DARM_MATH_CM33
 *   -DTF_LITE_STATIC_MEMORY
 *   -O2 -ffast-math
 *   Do NOT define DESKTOP_SHIM.
 *
 * CSV format expected (no header, comma-separated):
 *   acc,acoustic,fx,fy,fz        (one row per sample, float values)
 *   0.003421,0.000812,-1.234,2.456,-0.789
 *   ...
 *
 * The CSV must contain the cutting-segment signal already extracted
 * (i.e. the output of cwt_mcu's cutting mask / extract_cutting_signal
 *  applied on the host before transfer, or raw data if the MCU applies
 *  the mask — see APPLY_CUTTING_MASK below).
 *
 * UART protocol (INPUT_SOURCE = UART_CSV):
 *   1. MCU prints "READY\r\n" on boot
 *   2. Host sends CSV rows at 115200 baud (LPUART0 → USB debugger)
 *   3. Host sends "END\r\n" to signal end of data
 *   4. MCU prints "Predicted wear: XX.X um\r\n"
 *
 * Python host script:
 *   python experiments/phase6_deployment/send_csv_uart.py \
 *       --port /dev/tty.usbmodemXXXX \
 *       --csv  data/raw/Set4/sensordata/<file>.csv
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* NXP MCUXpresso SDK board support */
#include "board.h"
#include "pin_mux.h"
#include "clock_config.h"
#include "fsl_debug_console.h"   /* PRINTF / GETCHAR macros */
#include "fsl_lpuart.h"

/* CMSIS-DSP (needed by cwt_mcu.c) */
#include "arm_math.h"

/* Pipeline */
#include "sensor_pipeline.h"

/* Model weights — generated by:
 *   xxd -i checkpoints/onnx/phase4_multiscale_sgdm_best_25_int8.tflite \
 *       > phase4_multiscale_sgdm_best_25_model_data.h
 *   sed -i 's/phase4_multiscale_sgdm_best_25_int8_tflite/g_model_data/g' \
 *       phase4_multiscale_sgdm_best_25_model_data.h
 * Copy into the MCUXpresso project source tree alongside this file. */
#include "phase4_multiscale_sgdm_best_25_model_data.h"

/* ── Configuration ────────────────────────────────────────────────────── */

/* Set to 1 to receive CSV over UART, 0 to use embedded test vector */
#define INPUT_SOURCE_UART   1

/* UART baud rate (LPUART0 → USB debugger virtual COM port) */
#define UART_BAUD           115200U

/* Maximum line length for CSV parsing */
#define MAX_LINE_BYTES      256U

/* ── Static memory pool ───────────────────────────────────────────────── */

/* Placed in main SRAM (512 KB).  The linker assigns this to .bss.
 * If the MCU has a secondary SRAM bank, place the scalogram there to
 * leave more room for the tensor arena:
 *   __attribute__((section(".sram_oc"))) static float g_scalogram[...]; */
static uint8_t g_pool[SENSOR_PIPELINE_POOL_BYTES];

/* ── UART CSV reader ──────────────────────────────────────────────────── */

/**
 * Read one text line from the debug UART into buf (max_len includes '\0').
 * Returns number of characters read (excluding '\0'), or -1 on overflow.
 */
static int uart_readline(char *buf, size_t max_len)
{
    size_t n = 0;
    while (n < max_len - 1) {
        char c = (char)GETCHAR();
        if (c == '\n') break;
        if (c == '\r') continue;   /* skip carriage return */
        buf[n++] = c;
    }
    buf[n] = '\0';
    return (n == max_len - 1) ? -1 : (int)n;
}

/**
 * Parse one CSV row into the five channel accumulators.
 * Row format: "acc,acoustic,fx,fy,fz"
 * Returns 0 on success, -1 on parse error.
 */
static int parse_csv_row(const char *line,
                          float *acc, float *acoustic,
                          float *fx,  float *fy, float *fz)
{
    return (sscanf(line, "%f,%f,%f,%f,%f", acc, acoustic, fx, fy, fz) == 5) ? 0 : -1;
}

/* ── Main ─────────────────────────────────────────────────────────────── */

int main(void)
{
    /* ── Board init ─────────────────────────────────────────────────── */
    BOARD_InitBootPins();
    BOARD_InitBootClocks();
    BOARD_InitBootPeripherals();
    BOARD_InitDebugConsole();   /* LPUART0 @ UART_BAUD baud → USB */

    PRINTF("\r\n=== Tool Wear Prediction Pipeline ===\r\n");
    PRINTF("Model: MultiScaleSensorCNN INT8 TFLite  (%u KB flash)\r\n",
           (unsigned)(g_model_data_len / 1024));
    PRINTF("SRAM pool: %u KB\r\n",
           (unsigned)(sizeof(g_pool) / 1024));

    /* ── Pointers into pool ─────────────────────────────────────────── */
    /* The signal buffer is the first MAX_SIGNAL_SAMPLES floats of the pool.
     * main() reads all 5 channels into temporary storage here, one at a time,
     * then hands each column to sensor_pipeline_cwt_channel(). */
    float *signal = (float *)g_pool;   /* 396 KB — reused for all 5 channels */

    /* ── Read sensor data ───────────────────────────────────────────── */

#if INPUT_SOURCE_UART
    /* ── UART CSV receive ─────────────────────────────────────────── */
    /* Buffer all rows first (up to MAX_SIGNAL_SAMPLES), storing each
     * channel interleaved, then extract columns one at a time for CWT.
     *
     * Layout: signal[row * 5 + ch] = value  — 5 channels × N rows
     * This fits in the 396 KB signal buffer:
     *   99,000 rows × 5 channels × 4 bytes = 1.98 MB  → too large to buffer all.
     *
     * Alternative strategy (used here): two-pass UART receive.
     *   Pass 1: count rows, discard values.
     *   Pass 2: re-send and store only one channel column at a time.
     *
     * For a thesis demo it is simpler to send the CSV once and store the
     * full 5-channel interleaved data, limiting max signal length to:
     *   396 KB / (5 channels × 4 bytes) = 19,800 samples  (~12 s at 1625 Hz)
     * which covers most MATWI cutting segments. Extend g_pool if needed.
     */
    static const size_t MAX_ROWS = (SENSOR_PIPELINE_MAX_SAMPLES / 5);
    /* Re-interpret signal buffer as interleaved 5-channel data */
    float (*rows)[5] = (float (*)[5])(void *)signal;

    PRINTF("READY\r\n");
    PRINTF("Send CSV (acc,acoustic,fx,fy,fz), one row per line. "
           "Send END when done.\r\n");

    char  line[MAX_LINE_BYTES];
    int   n_rows = 0;

    while (n_rows < (int)MAX_ROWS) {
        int len = uart_readline(line, sizeof(line));
        if (len < 0) {
            PRINTF("[rx] Line too long — skipped\r\n");
            continue;
        }
        if (strncmp(line, "END", 3) == 0) break;
        if (len == 0) continue;   /* blank line */

        if (parse_csv_row(line,
                          &rows[n_rows][0], &rows[n_rows][1],
                          &rows[n_rows][2], &rows[n_rows][3],
                          &rows[n_rows][4]) == 0) {
            n_rows++;
        } else {
            PRINTF("[rx] Bad row %d: '%s' — skipped\r\n", n_rows, line);
        }
    }
    PRINTF("Received %d samples\r\n", n_rows);

    if (n_rows < 64) {
        PRINTF("ERROR: not enough samples (need ≥64, got %d)\r\n", n_rows);
        return -1;
    }

    /* Run CWT for each channel, extracting the column from interleaved data */
    static float g_channel_tmp[SENSOR_PIPELINE_MAX_SAMPLES / 5];
    for (int ch = 0; ch < SENSOR_PIPELINE_N_CHANNELS; ch++) {
        for (int r = 0; r < n_rows; r++) {
            g_channel_tmp[r] = rows[r][ch];
        }
        PRINTF("CWT channel %d/%d...\r\n", ch + 1, SENSOR_PIPELINE_N_CHANNELS);
        SensorPipelineStatus s = sensor_pipeline_cwt_channel(
            g_pool, g_channel_tmp, n_rows, ch);
        if (s != SENSOR_PIPELINE_OK) {
            PRINTF("ERROR: CWT failed for channel %d (code %d)\r\n", ch, s);
            return -1;
        }
    }

#else  /* INPUT_SOURCE_UART == 0 — embedded test vector */

    /* ── Embedded test vector ───────────────────────────────────────── */
    /* Replace with a real recording during bring-up validation.
     * Generate test vectors on the host:
     *   python experiments/cwt_c/validate_mcu.py --n 1 --seed 42
     * then embed the raw float32 CSV as a C array using xxd. */
    extern const float g_test_signal_ch0[];
    extern const int   g_test_signal_n;

    PRINTF("Using embedded test vector (%d samples)\r\n", g_test_signal_n);
    /* Only channel 0 for smoke-test — extend for full 5-channel validation */
    memcpy(signal, g_test_signal_ch0, g_test_signal_n * sizeof(float));

    SensorPipelineStatus s0 = sensor_pipeline_cwt_channel(
        g_pool, signal, g_test_signal_n, 0);
    if (s0 != SENSOR_PIPELINE_OK) {
        PRINTF("ERROR: CWT channel 0 failed\r\n");
        return -1;
    }
    /* Zero remaining channels so inference runs (scalogram is still valid) */
    float *scalo = sensor_pipeline_scalogram_ptr(g_pool);
    memset(scalo + 64 * 64, 0, 4 * 64 * 64 * sizeof(float));

#endif  /* INPUT_SOURCE_UART */

    /* ── Initialise TFLite Micro (reuses signal buffer as tensor arena) ── */
    PRINTF("Initialising TFLite Micro...\r\n");
    SensorPipeline *pipeline = sensor_pipeline_init(
        g_pool, sizeof(g_pool), g_model_data);
    if (!pipeline) {
        PRINTF("ERROR: pipeline init failed\r\n");
        return -1;
    }

    /* ── Run inference ───────────────────────────────────────────────── */
    PRINTF("Running inference...\r\n");
    float wear_um = 0.0f;
    SensorPipelineStatus status = sensor_pipeline_infer(pipeline, &wear_um);
    if (status != SENSOR_PIPELINE_OK) {
        PRINTF("ERROR: inference failed (code %d)\r\n", status);
        return -1;
    }

    /* ── Result ─────────────────────────────────────────────────────── */
    PRINTF("\r\n========================================\r\n");
    PRINTF("Predicted tool wear: %.1f um\r\n", wear_um);
    PRINTF("========================================\r\n");

    /* Halt */
    while (1) { __asm volatile("wfi"); }
    return 0;
}
