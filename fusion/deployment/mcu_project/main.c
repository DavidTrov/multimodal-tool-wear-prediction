/**
 * main.c — FRDM-MCXN947 application entry point.
 *
 * Receives sensor CSV columns + a tool flank image over UART, computes CWT
 * on the MCU, runs the full fusion model (image + scalogram → wear), and
 * prints the result.
 *
 * Hardware: NXP FRDM-MCXN947  (Cortex-M33, 416 KB SRAM + 96 KB SRAMX, 2 MB flash)
 * SDK:      MCUXpresso SDK with eIQ middleware and CMSIS-DSP
 *
 * Build flags (MCUXpresso project properties → C/C++ Build → Settings):
 *   -DARM_MATH_CM33
 *   -DDESKTOP_SHIM
 *   -DTF_LITE_STATIC_MEMORY
 *   -O2 -ffast-math
 *
 * Model: fusion_fp32_dedup_full_integer_quant.tflite
 *   Inputs:  image     [1, 224, 224, 3] INT8 NHWC
 *            scalogram [1,  64,  64, 5] INT8 NHWC  (from CWT, transposed in infer)
 *   Output:  wear      [1, 1]           INT8 (dequantised to float µm)
 *   Peak arena: ~370 KB (fits in the 391 KB pool)
 *   Flash:  1.2 MB (fits in 2 MB)
 *
 * UART protocol (per-channel, 115200 baud):
 *   1. MCU prints "READY\r\n" on boot
 *   2. For each channel n = 0..4:
 *      a. MCU prints "SEND_CH{n}\r\n"
 *      b. Host sends one float per line (the channel column), then "END\r\n"
 *      c. MCU computes CWT for channel n
 *   3. MCU initialises TFLite Micro, prints quantisation params
 *   4. MCU prints "SEND_IMAGE\r\n"
 *   5. Host sends exactly 150,528 raw INT8 bytes (224×224×3, NHWC, no header)
 *   6. MCU prints "Predicted tool wear: XX.X um\r\n"
 *
 * Python host script:
 *   python experiments/phase6_deployment/send_fusion_uart.py \
 *       --port /dev/tty.usbmodemXXXX \
 *       --csv  data/raw/Set4/sensordata/<file>.csv \
 *       --image data/raw/Set4/<flank_image>.jpg \
 *       --set-id 4
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* NXP MCUXpresso SDK board support */
#include "board.h"
#include "pin_mux.h"
#include "clock_config.h"
#include "fsl_debug_console.h"   /* PRINTF / GETCHAR macros */
#include "fsl_lpuart.h"

/* Pipeline */
#include "sensor_pipeline.h"

/* Model weights — fusion model (image + CWT scalogram → tool wear).
 * Generated by:
 *   xxd -i "checkpoints/fusion_tflite/fusion_fp32_dedup_full_integer_quant.tflite" \
 *       > fusion_model_data.h
 * then the array/length identifiers were renamed to g_model_data / g_model_data_len. */
#include "fusion_model_data.h"

/* ── Configuration ────────────────────────────────────────────────────── */

/* UART baud rate (LPUART0 → USB debugger virtual COM port) */
#define UART_BAUD           115200U

/* Maximum line length for CSV parsing (single float per line) */
#define MAX_LINE_BYTES      64U

/* ── Static memory ────────────────────────────────────────────────────── */

/* Main SRAM pool: signal buffer (384 KB) + CWT workspace (16 KB) = 391 KB.
 * After CWT, this entire region is reused as the TFLite tensor arena. */
static uint8_t g_pool[SENSOR_PIPELINE_POOL_BYTES];

/* Scalogram placed in SRAMX (96 KB at 0x04000000) to keep it out of main SRAM.
 * Uses .noinit.$SRAMX (not .bss.$SRAMX) so the startup code does NOT try to
 * zero-initialise it before BOARD_InitBootClocks() has enabled the SRAMX domain.
 * We zero it manually in main() after board init. */
__attribute__((section(".noinit.$SRAMX")))
static float g_scalogram[SENSOR_PIPELINE_SCALOGRAM_FLOATS];

/* ── UART helpers ─────────────────────────────────────────────────────── */

/**
 * Read one text line from the debug UART into buf (max_len includes '\0').
 * Returns number of characters read (excluding '\0'), or -1 on overflow.
 */
static int uart_readline(char *buf, size_t max_len)
{
    size_t n = 0;
    while (n < max_len - 1) {
        char c = (char)GETCHAR();
        if (c == '\n') break;
        if (c == '\r') continue;   /* skip carriage return */
        buf[n++] = c;
    }
    buf[n] = '\0';
    return (n == max_len - 1) ? -1 : (int)n;
}

/* ── Main ─────────────────────────────────────────────────────────────── */

int main(void)
{
    /* ── Board init ─────────────────────────────────────────────────── */
    BOARD_InitBootPins();
    BOARD_InitBootClocks();
    BOARD_InitDebugConsole();   /* LPUART0 @ UART_BAUD baud → USB */

    /* Zero-init scalogram now that SRAMX is powered/clocked after board init. */
    memset(g_scalogram, 0, sizeof(g_scalogram));

    PRINTF("\r\n=== Tool Wear Prediction Pipeline ===\r\n");
    PRINTF("Model: fusion INT8 TFLite  (%u KB flash)\r\n",
           (unsigned)(g_model_data_len / 1024));
    PRINTF("SRAM pool: %u KB  SRAMX scalogram: %u KB\r\n",
           (unsigned)(sizeof(g_pool) / 1024),
           (unsigned)(sizeof(g_scalogram) / 1024));

    PRINTF("READY\r\n");

    /* ── Receive one channel at a time, run CWT per channel ─────────── */
    /*
     * The signal buffer (pool[0..384KB)) holds one channel's samples at a time.
     * After CWT the slice is stored in g_scalogram (SRAMX); the signal buffer
     * is overwritten by the next channel. No interleaved storage needed.
     * Max samples per channel: SENSOR_PIPELINE_MAX_SAMPLES = 96,000 (~59 s).
     */
    float *signal = (float *)g_pool;
    int    n_samples_per_ch = 0;   /* same for all channels */
    char   line[MAX_LINE_BYTES];

    static const char *const CH_NAMES[SENSOR_PIPELINE_N_CHANNELS] =
        { "acc", "acoustic", "fx", "fy", "fz" };

    for (int ch = 0; ch < SENSOR_PIPELINE_N_CHANNELS; ch++) {
        PRINTF("SEND_CH%d\r\n", ch);
        PRINTF("Send %s column as one float per line, then END\r\n", CH_NAMES[ch]);

        int n = 0;
        while (n < (int)SENSOR_PIPELINE_MAX_SAMPLES) {
            int len = uart_readline(line, sizeof(line));
            if (len < 0) {
                PRINTF("[rx] Line too long — skipped\r\n");
                continue;
            }
            if (strncmp(line, "END", 3) == 0) break;
            if (len == 0) continue;   /* blank line */

            float val;
            if (sscanf(line, "%f", &val) == 1) {
                signal[n++] = val;
            } else {
                PRINTF("[rx] Bad value '%s' — skipped\r\n", line);
            }
        }

        if (n < 64) {
            PRINTF("ERROR: channel %d: not enough samples (need >=64, got %d)\r\n",
                   ch, n);
            return -1;
        }
        if (ch == 0) {
            n_samples_per_ch = n;
        } else if (n != n_samples_per_ch) {
            PRINTF("WARNING: channel %d has %d samples (expected %d)\r\n",
                   ch, n, n_samples_per_ch);
        }

        PRINTF("Channel %d/%d (%s): %d samples. Computing CWT...\r\n",
               ch + 1, SENSOR_PIPELINE_N_CHANNELS, CH_NAMES[ch], n);

        SensorPipelineStatus s = sensor_pipeline_cwt_channel(
            g_pool, g_scalogram, signal, n, ch);
        if (s != SENSOR_PIPELINE_OK) {
            PRINTF("ERROR: CWT failed for channel %d (code %d)\r\n", ch, s);
            return -1;
        }
        PRINTF("CWT channel %d OK\r\n", ch);
    }

    PRINTF("All CWT channels done (%d samples each)\r\n", n_samples_per_ch);

    /* ── Initialise TFLite Micro (pool → tensor arena) ───────────────── */
    PRINTF("Initialising TFLite Micro...\r\n");
    SensorPipeline *pipeline = sensor_pipeline_init(
        g_pool, sizeof(g_pool), g_scalogram, g_model_data);
    if (!pipeline) {
        PRINTF("ERROR: pipeline init failed\r\n");
        return -1;
    }

    /* ── Receive image from host ─────────────────────────────────────── */
    /* sensor_pipeline_init() printed scale/zero_point for the image input.
     * The host crops, resizes to 224×224, ImageNet-normalises, quantises to
     * INT8, then sends exactly SENSOR_PIPELINE_IMG_BYTES raw bytes over UART. */
    PRINTF("SEND_IMAGE\r\n");

    int8_t *img_buf = sensor_pipeline_image_input_ptr(pipeline);
    for (uint32_t i = 0; i < SENSOR_PIPELINE_IMG_BYTES; i++) {
        img_buf[i] = (int8_t)(uint8_t)GETCHAR();
    }
    PRINTF("Image received OK (%u bytes)\r\n",
           (unsigned)SENSOR_PIPELINE_IMG_BYTES);

    /* ── Run inference ───────────────────────────────────────────────── */
    PRINTF("Running inference...\r\n");
    float wear_um = 0.0f;
    SensorPipelineStatus status = sensor_pipeline_infer(pipeline, g_scalogram, &wear_um);
    if (status != SENSOR_PIPELINE_OK) {
        PRINTF("ERROR: inference failed (code %d)\r\n", status);
        return -1;
    }

    /* ── Result ─────────────────────────────────────────────────────── */
    PRINTF("\r\n========================================\r\n");
    PRINTF("Predicted tool wear: %.1f um\r\n", wear_um);
    PRINTF("========================================\r\n");

    /* Halt */
    while (1) { __asm volatile("wfi"); }
    return 0;
}
